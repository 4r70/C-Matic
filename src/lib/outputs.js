import { calc, flatProducts, fmt } from './calc.js';
import { PRODUCER, YEAR } from '../data/seed.js';

const round = (n, d = 3) => (n == null ? null : +n.toFixed(d));

export function buildRows({ conn, data, hierarchy }) {
  const prods = flatProducts(hierarchy);
  const rows = [];
  conn.products.forEach((pid) => {
    const p = prods.find((x) => x.id === pid);
    if (!p) return;
    conn.periods.forEach((q) => {
      const ds = data[`${pid}:${q}`];
      if (!ds) return;
      const c = calc(ds);
      const f = conn.fields;
      const row = { product: p.name, cn_code: p.cn, period: `${YEAR}-${q}` };
      if (f.includes('plant')) { row.installation = p.factory; row.process = p.processes.join(' + '); }
      if (f.includes('production')) row.production_t = ds.production;
      if (f.includes('intensity')) row.embedded_tco2e_per_t = round(c.intensity);
      if (f.includes('direct')) { row.direct_tco2e = Math.round(c.direct); row.direct_tco2e_per_t = round(c.directInt); }
      if (f.includes('indirect')) { row.indirect_tco2e = c.indirect == null ? null : Math.round(c.indirect); row.grid_ef_tco2_per_mwh = ds.gridEF; }
      if (f.includes('energy')) { row.electricity_mwh = round(c.elecMWh, 1); row.natural_gas_nm3 = ds.gasNm3; row.other_fuels_t = ds.fuelT; }
      if (f.includes('materials')) { row.scrap_t = ds.scrapT; row.pig_iron_t = ds.pigIronT; row.ferroalloys_t = ds.ferroalloysT; row.precursor_t = ds.precursorT; }
      if (f.includes('commercial')) row.avg_price_eur_per_t = { bolts: 1180, wirerod: 610, rebar: 560 }[pid] || 700;
      rows.push(row);
    });
  });
  return rows;
}

export const toJSON = (rows, importer, version = 1) =>
  JSON.stringify({
    schema: 'cmatic.cbam.dataset/1.0',
    illustrative: true,
    producer: { name: PRODUCER.company, country: 'TR' },
    recipient: importer.name,
    reporting_year: YEAR,
    dataset_version: version,
    generated_at: '2026-11-11T17:20:00+02:00',
    items: rows,
  }, null, 2);

export const toCSV = (rows) => {
  if (!rows.length) return '';
  const cols = [...new Set(rows.flatMap((r) => Object.keys(r)))];
  return [cols.join(','), ...rows.map((r) => cols.map((c) => JSON.stringify(r[c] ?? '')).join(','))].join('\n');
};

const LABELS = {
  cn_code: 'CN code', production_t: 'Production (t)', embedded_tco2e_per_t: 'Embedded tCO₂e / t', direct_tco2e: 'Direct tCO₂e', direct_tco2e_per_t: 'Direct tCO₂e / t',
  indirect_tco2e: 'Indirect tCO₂e', grid_ef_tco2_per_mwh: 'Grid EF tCO₂/MWh', electricity_mwh: 'Electricity MWh', natural_gas_nm3: 'Natural gas Nm³', other_fuels_t: 'Other fuels (t)',
  scrap_t: 'Scrap (t)', pig_iron_t: 'Pig iron (t)', ferroalloys_t: 'Ferroalloys (t)', precursor_t: 'Precursor (t)', avg_price_eur_per_t: 'Avg price EUR/t',
};
export const prettyKey = (k) => LABELS[k] || k.charAt(0).toUpperCase() + k.slice(1).replace(/_/g, ' ');

export function download(filename, content, mime = 'text/plain') {
  const url = URL.createObjectURL(new Blob([content], { type: mime }));
  const a = document.createElement('a');
  a.href = url; a.download = filename; document.body.appendChild(a); a.click(); a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

export function htmlDoc(rows, title) {
  const cols = [...new Set(rows.flatMap((r) => Object.keys(r)))];
  return `<html><head><meta charset="utf-8"><title>${title}</title><style>body{font-family:Arial;padding:24px}table{border-collapse:collapse}td,th{border:1px solid #bbb;padding:4px 8px;font-size:12px}th{background:#eef6ff}</style></head><body><h2>${title}</h2><p>Illustrative values. Generated by C-Matic (demo).</p><table><tr>${cols.map((c) => `<th>${prettyKey(c)}</th>`).join('')}</tr>${rows.map((r) => `<tr>${cols.map((c) => `<td>${typeof r[c] === 'number' ? fmt(r[c], r[c] % 1 ? 3 : 0) : r[c] ?? ''}</td>`).join('')}</tr>`).join('')}</table></body></html>`;
}
